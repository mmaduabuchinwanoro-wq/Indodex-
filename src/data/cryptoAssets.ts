export function getAssetBySymbol(symbol: string): CryptoAsset | undefined {
  return SUPPORTED_ASSETS.find((a) => a.symbol.toUpperCase() === symbol.toUpperCase());
}

export function formatCurrency(value: number, minDecimals = 2, maxDecimals = 2): string {
  if (value === 0) return '$0.00';
  if (value < 0.01 && value > 0) {
    return `$${value.toFixed(6)}`;
  }
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    minimumFractionDigits: minDecimals,
    maximumFractionDigits: maxDecimals,
  }).format(value);
}

export function formatCryptoAmount(amount: number, symbol: string): string {
  const asset = getAssetBySymbol(symbol);
  const decimals = asset ? Math.min(asset.decimals, 6) : 4;
  if (amount === 0) return `0 ${symbol}`;
  return `${amount.toLocaleString('en-US', { maximumFractionDigits: decimals })} ${symbol}`;
}
